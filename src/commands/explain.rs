use sequoia_openpgp as openpgp;
use openpgp::Result;

use crate::cli::explain;
use crate::Sq;

struct Term {
    name: String,
    synonyms: Vec<String>,
    body: String
}

impl Term {
    fn contains_word(&self, word: &str) -> bool {
        if self.name.contains(word) {
            return true;
        } else {
            return self.synonyms.iter().any(|x| x.contains(word));
        }
    }
}

pub fn dispatch(_sq: Sq, c: explain::Command) -> Result<()> {
    let terms = vec![
        Term {
            name: String::from("binding"),
            synonyms: Vec::new(),
            body: String::from(
                "A binding ties a certificate and User ID together."
            )
        },
        Term {
            name: String::from("local trust root"),
            synonyms: Vec::new(),
            body: String::from(
                "A special certificate tied to the computer and its \
                 user. It is created if it does not exist and it is \
                 at the top of the trust chain for all the local \
                 operations performed by sequoia-sq. Its purpose is to \
                 provide provenance for all manners of key \
                 management. It is self-signed, and it is typically \
                 not shared with others. Local trust root would \
                 certify any key generated by the user."
            )
        },
    ];
    let explain_terms: Vec<String> = c.explain_terms.iter()
        .map(|term| term.to_lowercase())
        .collect();
    for term in &terms {
        if explain_terms.iter().all(|x| term.contains_word(x)) {
            println!("- {}", term.name);
            println!("{}\n", term.body);
        }
    }
    Ok(())
}
